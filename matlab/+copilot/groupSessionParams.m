function grouped = groupSessionParams(flat, isResume, emptyMode)
%groupSessionParams  Convert a flat session payload to SDK protocol 4.
%
%   grouped = copilot.groupSessionParams(flat, isResume, emptyMode)
%
%   copilot.SessionConfig.toStruct() builds the flat (v1-style) payload that
%   session.create and session.resume used before SDK protocol 4.  Protocol
%   4 groups most options into objects such as inference, tools and
%   permissions, and rejects the old flat keys.  CopilotClient calls this
%   helper on the final payload right before sending, so callers keep using
%   the same SessionConfig options.
%
%   Rules:
%     * Root keys (sessionId, model, systemMessage, ...) stay at the top level.
%     * Known flat keys move to group.member (for example streaming becomes
%       events.streaming and requestPermission becomes permissions.request).
%     * Unknown keys stay at the root; empty ([]) values are skipped.
%     * Members of an already grouped object win over flat keys.
%     * configDir becomes configDirectory; on resume disableResume becomes
%       suppressResumeEvent and create-only options are dropped.
%     * A legacy single "provider" becomes the named provider "default".
%     * mcp.envValueMode is "direct" whenever MCP servers are sent.
%   When emptyMode is true the "empty" client mode defaults are applied
%   underneath the caller's values.

    if nargin < 2
        isResume = false;
    end
    if nargin < 3
        emptyMode = false;
    end

    [wireMap, rootKeys, groupNames] = wireTables();

    grouped = struct();
    groups = struct();
    provider = [];
    model = [];
    keys = fieldnames(flat);

    % First pass: members of objects that are already grouped win.
    for i = 1:numel(keys)
        key = keys{i};
        value = flat.(key);
        if any(strcmp(key, groupNames)) && isstruct(value) && isscalar(value)
            members = fieldnames(value);
            for j = 1:numel(members)
                groups = addMember(groups, key, members{j}, value.(members{j}));
            end
        end
    end

    % Second pass: place every flat key.
    for i = 1:numel(keys)
        key = keys{i};
        value = flat.(key);
        isGroup = any(strcmp(key, groupNames));
        if (isGroup && isstruct(value) && isscalar(value)) || isNullValue(value)
            continue;
        end
        if strcmp(key, 'model')
            model = value;
        end

        if strcmp(key, 'configDir')
            grouped = addRoot(grouped, 'configDirectory', value);
        elseif strcmp(key, 'disableResume') && isResume
            grouped = addRoot(grouped, 'suppressResumeEvent', value);
        elseif strcmp(key, 'provider')
            provider = value;
        elseif isResume && any(strcmp(key, {'trustWorkingDirectory', 'refreshCustomInstructions'}))
            continue;  % create-only options
        elseif ~isResume && strcmp(key, 'openCanvases')
            continue;  % resume-only option
        elseif any(strcmp(key, rootKeys))
            grouped = addRoot(grouped, key, value);
        elseif isKey(wireMap, key)
            dest = strsplit(wireMap(key), '.');
            groups = addMember(groups, dest{1}, dest{2}, value);
        elseif isGroup
            continue;  % a group name with a non-object value is rejected by protocol 4
        else
            grouped = addRoot(grouped, key, value);  % unknown keys stay at the root
        end
    end

    % Legacy single BYOK provider => named provider "default".  Explicit
    % named providers / default provider / capi settings win.
    if isstruct(provider) && isscalar(provider) ...
            && ~hasMember(groups, 'inference', 'providers') ...
            && ~hasMember(groups, 'inference', 'defaultProvider') ...
            && ~hasMember(groups, 'github', 'capi')
        modelKeys = {'modelId', 'wireModel', 'maxPromptTokens', ...
                     'maxContextWindowTokens', 'maxOutputTokens', 'capabilities'};
        connection = struct('name', 'default');
        modelFields = struct();
        fields = fieldnames(provider);
        for j = 1:numel(fields)
            name = fields{j};
            fieldValue = provider.(name);
            if strcmp(name, 'name') || isNullValue(fieldValue)
                continue;
            elseif any(strcmp(name, modelKeys))
                modelFields.(name) = fieldValue;
            else
                connection.(name) = fieldValue;
            end
        end
        groups = addMember(groups, 'inference', 'providers', {connection});
        groups = addMember(groups, 'inference', 'defaultProvider', 'default');
        groups = addMember(groups, 'github', 'capi', struct('enabled', false));
        modelNames = fieldnames(modelFields);
        if ~isempty(modelNames) && ~isempty(model)
            entry = struct('provider', 'default', 'id', model);
            for j = 1:numel(modelNames)
                entry.(modelNames{j}) = modelFields.(modelNames{j});
            end
            groups = addMember(groups, 'inference', 'models', {entry});
        end
    end

    if hasMember(groups, 'mcp', 'servers')
        groups = addMember(groups, 'mcp', 'envValueMode', 'direct');
    end

    if emptyMode
        groups = addMember(groups, 'experiments', 'enableExperimentalMode', false);
        groups = addMember(groups, 'github', 'telemetryEnabled', false);
        groups = addMember(groups, 'mcp', 'oauthTokenStorage', 'in-memory');
        groups = addMember(groups, 'state', 'skipEmbeddingRetrieval', true);
        groups = addMember(groups, 'state', 'embeddingCacheStorage', 'in-memory');
        groups = addMember(groups, 'state', 'enableCrossSessionStore', false);
        groups = addMember(groups, 'state', 'memory', struct('enabled', false));
        groups = addMember(groups, 'instructions', 'onDemandDiscovery', false);
        groups = addMember(groups, 'hooks', 'enableRepositoryHooks', false);
        groups = addMember(groups, 'git', 'enableHostGitOperations', false);
    end

    for i = 1:numel(groupNames)
        name = groupNames{i};
        if isfield(groups, name)
            grouped.(name) = groups.(name);
        end
    end
end

function groups = addMember(groups, group, member, value)
    % Add group.member unless the value is empty or the member exists.
    if isNullValue(value)
        return;
    end
    if ~isfield(groups, group)
        groups.(group) = struct();
    end
    if ~isfield(groups.(group), member)
        groups.(group).(member) = value;
    end
end

function tf = hasMember(groups, group, member)
    tf = isfield(groups, group) && isfield(groups.(group), member);
end

function s = addRoot(s, key, value)
    if ~isfield(s, key)
        s.(key) = value;
    end
end

function tf = isNullValue(value)
    % [] means "not set"; NaN is kept and encodes as JSON null.
    tf = isnumeric(value) && isempty(value);
end

